#!/usr/bin/env python3
"""Regenerate TUI golden frames.

For each (state, variant, size, display timezone) combination:
  1. Invoke `cctally tui --render-once
     --snapshot-module <path> --variant <v> --force-size WxH --no-color
     --tz <zone>`
  2. Capture stdout
  3. Write to tests/fixtures/tui/golden/<state>_<variant>_<WxH>.txt

Eyeball each .txt after generation: misaligned borders, tag-literal
leakage, or crash output means fix the renderer (not the golden).

``--manifest`` prints the combination list as four-column TSV — state,
variant, size, display timezone — and writes nothing. `bin/cctally-tui-test`
reads that instead of carrying its own copy of the list (#769 S4 #796): the
two lists had drifted to 24 combinations in the harness against 9 here, so
fifteen of the renders the suite checks were regenerated by nobody.
"""
import os
import pathlib
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).parent.parent
FIX = REPO / "tests" / "fixtures" / "tui"
GOLDEN = FIX / "golden"
BIN = REPO / "bin" / "cctally"

#: `(state, variant, size, display timezone)`. Every combination carries an
#: explicit zone, and the process runs under `TZ=Etc/UTC`. Twenty-three
#: render at `Etc/UTC`; `iana_tz` is the deliberate regression case for an
#: explicit IANA zone and must keep rendering `America/New_York`.
#:
#: The zone is spelled `Etc/UTC` and never `UTC`, because `_local_tz_name`
#: accepts only a value containing a slash and falls back to host-local
#: otherwise — so `TZ=UTC` is wrong rather than merely inconsistent. Before
#: this pinning, twenty-one of these combinations inherited whatever
#: `display.tz` the ambient data directory carried, so a maintainer with that
#: key set regenerated a different zone into the golden.
COMBOS = [
    ("warn", "conventional", "120x36", "Etc/UTC"),
    ("warn", "conventional", "100x30", "Etc/UTC"),
    ("warn", "expressive", "120x36", "Etc/UTC"),
    ("warn", "expressive", "100x30", "Etc/UTC"),
    ("ok", "conventional", "120x36", "Etc/UTC"),
    ("over", "conventional", "120x36", "Etc/UTC"),
    # #661 S2 section 3.2 / section 13: the 100% right-censored path on EVERY
    # consumer. `over` reads 92.4% and never reaches the cap, so no committed
    # fixture exercised the withheld projection on any TUI render path.
    ("censored", "conventional", "120x36", "Etc/UTC"),
    ("censored", "expressive", "120x36", "Etc/UTC"),
    # v2 additions
    ("filter_subscr", "conventional", "120x36", "Etc/UTC"),
    ("filter_empty", "conventional", "120x36", "Etc/UTC"),
    ("sort_cost", "conventional", "120x36", "Etc/UTC"),
    ("search_opus", "conventional", "120x36", "Etc/UTC"),
    ("modal_cw", "conventional", "120x36", "Etc/UTC"),
    ("modal_fc", "conventional", "120x36", "Etc/UTC"),
    # The explain modal over the censored underlay: the surface that stated
    # `no 24h-prior sample` for a state whose cause is the censoring.
    ("modal_fc_censored", "conventional", "120x36", "Etc/UTC"),
    ("modal_tr", "conventional", "120x36", "Etc/UTC"),
    ("modal_tr", "conventional", "100x30", "Etc/UTC"),
    ("modal_se", "conventional", "120x36", "Etc/UTC"),
    ("modal_se", "expressive", "120x36", "Etc/UTC"),
    # Phase C / Task C6 — freshness chip on stale current_week
    ("warn_stale", "conventional", "120x36", "Etc/UTC"),
    # F4 regression: an explicit IANA --tz must localize session-row times
    # (the legacy renderer rendered raw UTC for any non-"local" token).
    ("iana_tz", "conventional", "120x36", "America/New_York"),
    # #734: an in-place-credited subscription week, assembled from a seeded
    # store through the production builders rather than from hand-written
    # rows. The Trend panel and the Trend modal must show BOTH billing cycles.
    ("credited_week", "conventional", "120x36", "Etc/UTC"),
    ("credited_week", "expressive", "120x36", "Etc/UTC"),
    ("modal_tr_credited_week", "conventional", "120x36", "Etc/UTC"),
]


def emit_manifest(stream) -> None:
    """Print the combination list as four-column TSV.

    Side-effect-free by contract: the harness refuses a manifest run that
    wrote anything, and `GOLDEN.mkdir` therefore lives in `build()` rather
    than at import as it did before #796.
    """
    for state, variant, size, tz in COMBOS:
        stream.write(f"{state}\t{variant}\t{size}\t{tz}\n")


def build() -> None:
    GOLDEN.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="cctally-tui-builder-") as scratch:
        _build_into(scratch)


def _build_into(scratch: str) -> None:
    for state, variant, size, tz in COMBOS:
        mod = FIX / f"snapshot_{state}.py"
        assert mod.exists(), f"missing {mod}"
        out_file = GOLDEN / f"{state}_{variant}_{size}.txt"
        result = subprocess.run(
            [
                str(BIN), "tui", "--render-once",
                "--snapshot-module", str(mod),
                "--variant", variant,
                "--force-size", size,
                "--no-color",
                "--tz", tz,
            ],
            check=True,
            capture_output=True,
            text=True,
            env={
                **os.environ,
                "NO_COLOR": "1",
                # `TZ=UTC` was wrong rather than merely inconsistent:
                # `_local_tz_name` accepts only a value containing a slash and
                # otherwise falls back to host-local.
                "TZ": "Etc/UTC",
                # The suppressor every harness exports through
                # `bin/_lib-harness-env.sh`. Without it the three
                # `credited_week` combinations fail outright — this generator
                # runs `bin/cctally` from a git checkout, so the dev-checkout
                # auto-detection resolves a data directory the render is not
                # allowed to advance, and the run ends with `Error: not
                # authorized`. Those three renders could therefore never be
                # regenerated by this builder before #769 S4 #796.
                "CCTALLY_DISABLE_DEV_AUTODETECT": "1",
                # …and the scratch data directory that suppressor makes
                # mandatory here. Every harness exports the suppressor from
                # under a fake HOME; this generator has no fake HOME, so with
                # the suppressor alone `_init_paths_from_env` falls past the
                # dev-checkout branch to the PRODUCTION default
                # `~/.local/share/cctally` — the maintainer's live install,
                # which this render would then open, lock and write into.
                "CCTALLY_DATA_DIR": scratch,
                # The two detached post-command workers `bin/_lib-harness-env.sh`
                # suppresses for the same reason: both write markers, stamps and
                # logs into the data directory AFTER the command exits, so the
                # scratch directory would be removed underneath them.
                "CCTALLY_DISABLE_UPDATE_CHECK": "1",
                "CCTALLY_DISABLE_RETENTION_SWEEP": "1",
            },
        )
        out_file.write_text(result.stdout)
        print(f"wrote {out_file.relative_to(REPO)}")


def main(argv: list) -> int:
    """Exactly one optional flag; anything else is refused rather than ignored.

    `--manifest` used to be recognised by membership anywhere in `sys.argv`,
    with every other argument silently discarded. A typo'd flag therefore ran
    a full twenty-four-combination regeneration against the caller's tree
    instead of reporting that it was not understood.
    """
    if not argv:
        build()
        return 0
    if argv == ["--manifest"]:
        emit_manifest(sys.stdout)
        return 0
    print("usage: build-tui-fixtures.py [--manifest]", file=sys.stderr)
    print("unrecognised arguments: " + " ".join(argv), file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
